create table users (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    email varchar(190) not null unique,
    password_hash varchar(255) not null,
    role varchar(20) not null default 'CUSTOMER' check (role in ('CUSTOMER', 'ADMIN')),
    created_at timestamp not null default current_timestamp
);

create table addresses (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    label varchar(40),
    address_text varchar(500) not null,
    pincode char(6) not null,
    is_default boolean not null default false
);

create table services (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    unit varchar(10) not null check (unit in ('KG', 'ITEM')),
    price decimal(10,2) not null,
    active boolean not null default true
);

create table service_areas (
    id bigint generated by default as identity primary key,
    pincode char(6) not null unique,
    area_name varchar(100) not null,
    active boolean not null default true,
    latitude decimal(10,7),
    longitude decimal(10,7)
);

create table pickup_slots (
    id bigint generated by default as identity primary key,
    label varchar(100) not null,
    starts_at timestamp not null,
    ends_at timestamp not null,
    capacity integer not null,
    booked_count integer not null default 0,
    active boolean not null default true
);

create table delivery_agents (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    phone varchar(20) not null,
    vehicle_number varchar(30) not null,
    active boolean not null default true,
    created_at timestamp not null default current_timestamp
);

create table orders (
    id bigint generated by default as identity primary key,
    order_number varchar(30) not null unique,
    user_id bigint references users(id),
    address_id bigint references addresses(id),
    address_text varchar(500) not null,
    pincode char(6) not null,
    pickup_latitude decimal(10,7),
    pickup_longitude decimal(10,7),
    pickup_slot_id bigint not null references pickup_slots(id),
    delivery_agent_id bigint references delivery_agents(id),
    status varchar(30) not null check (status in ('BOOKED','PICKUP_ASSIGNED','OUT_FOR_PICKUP','PICKED_UP','AT_SHOP','CLEANING','READY_FOR_DELIVERY','OUT_FOR_DELIVERY','DELIVERED','CANCELLED')),
    payment_method varchar(30) not null default 'CASH_ON_DELIVERY' check (payment_method = 'CASH_ON_DELIVERY'),
    payment_status varchar(10) not null default 'PENDING' check (payment_status in ('PENDING','PAID')),
    estimated_total decimal(10,2) not null,
    actual_total decimal(10,2),
    estimated_delivery_at timestamp,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create table order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references orders(id),
    service_id bigint not null references services(id),
    quantity decimal(10,2) not null,
    unit_price decimal(10,2) not null,
    line_total decimal(10,2) not null
);

create table order_status_history (
    id bigint generated by default as identity primary key,
    order_id bigint not null references orders(id),
    status varchar(30) not null check (status in ('BOOKED','PICKUP_ASSIGNED','OUT_FOR_PICKUP','PICKED_UP','AT_SHOP','CLEANING','READY_FOR_DELIVERY','OUT_FOR_DELIVERY','DELIVERED','CANCELLED')),
    note varchar(255),
    created_at timestamp not null default current_timestamp
);

create table auth_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    token_hash char(64) not null unique,
    expires_at timestamp not null,
    created_at timestamp not null default current_timestamp
);

create index idx_orders_status_created on orders(status, created_at);
create index idx_orders_user on orders(user_id);
create index idx_history_order on order_status_history(order_id, created_at);
create index idx_auth_tokens_expiry on auth_tokens(expires_at);

